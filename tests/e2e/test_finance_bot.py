    async def test_forged_foreign_ids_never_read_modify_delete_or_assign(self):
        other = self.store.ensure_user(202)
        tag, _ = self.store.create_tag(other.id, "PRIVATE TAG")
        row = self.store.create_transaction(other.id, "income", 321, datetime.now(UTC), [tag.id], "PRIVATE COMMENT")
        for action in ["edit:", "delete:"]:
            await self.driver.click(data=action + row.id)
            self.assertIn("не найдена", self.driver.latest().text)
        self.assertNotIn("PRIVATE", self.driver.texts())
        await self.begin()
        prefix = self.driver.button("Далее").rsplit(":", 1)[0]
        await self.driver.click(data=prefix + ":" + tag.id)
        self.assertEqual(self.rows(), [])
        await self.to_comment()
        await self.finish()
        self.assertEqual(self.rows()[0].tags, ())
        self.assertEqual(self.store.get_transaction(other.id, row.id).comment, "PRIVATE COMMENT")
        await self.driver.click("Теги")
        token = self.driver.button("Создать тег").split(":")[1]
        for action in ["rename", "archive"]:
            await self.driver.click(data=f"t:{token}:{action}:{tag.id}")
            self.assertIn("не найдена", self.driver.latest().text)
        self.assertFalse(self.store.get_tag(other.id, tag.id).is_archived)
        self.assertEqual(self.store.get_tag(other.id, tag.id).name, "PRIVATE TAG")
        await self.driver.text("/start", user_id=202)
        await self.driver.click("Операции", user_id=202)
        self.assertIn("PRIVATE COMMENT", self.driver.texts(202))

