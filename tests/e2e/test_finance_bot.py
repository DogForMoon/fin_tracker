import asyncio
from datetime import UTC, datetime

from sqlalchemy import text

from tests.bot_case import BotCase


class FinanceBotTests(BotCase):
    async def begin(self, kind="expense", amount="125", at=None):
        await self.driver.text("/income" if kind == "income" else "/expense", at=at)
        await self.driver.text(amount)

    async def to_comment(self):
        await self.driver.click("Далее")

    async def finish(self):
        await self.driver.click("Далее")

    async def create(self, kind="expense", amount="125", comment=None):
        await self.begin(kind, amount)
        await self.to_comment()
        if comment is not None:
            await self.driver.text(comment)
        await self.finish()
        return self.rows()[0]

    async def edit(self, row):
        await self.driver.click(data="edit:" + row.id)

    async def edit_to_comment(self, row):
        await self.edit(row)
        await self.driver.click("Далее")
        await self.driver.click("Далее")
        await self.driver.click("Далее")

    async def test_income_multiple_tags_comment_and_expense_optional_skip(self):
        first, _ = self.store.create_tag(self.user.id, "Работа")
        second, _ = self.store.create_tag(self.user.id, "Бонус")
        await self.driver.text("/start")
        await self.driver.click("Получил")
        await self.driver.text("125.5")
        await self.driver.click("Работа")
        await self.driver.click("Бонус")
        await self.to_comment()
        await self.driver.text("salary")
        await self.finish()
        income = self.rows()[0]
        self.assertEqual((income.kind, income.amount_kopecks, income.comment), ("income", 12550, "salary"))
        self.assertEqual({tag.id for tag in income.tags}, {first.id, second.id})
        await self.driver.click("Потратил")
        await self.driver.text("125")
        await self.to_comment()
        await self.finish()
        expense = next(row for row in self.rows() if row.kind == "expense")
        self.assertEqual((expense.amount_kopecks, expense.tags, expense.comment), (12500, (), None))
        await self.driver.click("Операции")
        self.assertIn("Расход: 125,00 ₽", self.driver.texts())
        self.assertIn("Доход: 125,50 ₽", self.driver.texts())
        self.assertIn("salary", self.driver.texts())

    async def test_invalid_amounts_retry_and_large_amount_exact(self):
        await self.driver.text("/expense")
        amount_next = self.driver.button("Далее")
        for invalid in ["0", "0.00", "-1", "+1", "1.", "1,234", "1e3", " ", "word", "١"]:
            await self.driver.text(invalid)
            self.assertEqual(self.rows(), [])
            self.assertIn("сумм", self.driver.latest().text.lower())
        value = "9" * 4093 + ".01"
        await self.driver.text(value)
        self.assertNotEqual(self.driver.button("Далее"), amount_next)
        await self.to_comment()
        await self.finish()
        self.assertEqual(self.rows()[0].amount_kopecks, int("9" * 4093) * 100 + 1)
        await self.driver.click("Операции")
        self.assertTrue(all(len(message.text or "") <= 4096 for message in self.driver.session.messages))

    async def test_navigation_date_midnight_cancel_and_new_start(self):
        started = datetime(2026, 10, 14, 20, 59, 59, tzinfo=UTC)
        await self.begin(at=started)
        tag_next = self.driver.button("Далее")
        await self.driver.click("Назад")
        self.assertIn("125,00 ₽", self.driver.latest().text)
        await self.driver.click("Назад")
        await self.driver.click("Получил")
        await self.driver.click("Далее")
        await self.driver.click(data=tag_next)
        await self.finish()
        row = self.rows()[0]
        self.assertEqual((row.kind, row.amount_kopecks, row.occurred_at), ("income", 12500, started))
        await self.driver.click("Операции")
        self.assertIn("14.10.2026 23:59", self.driver.latest().text)
        await self.begin()
        cancel = self.driver.button("Отменить")
        await self.driver.click(data=cancel)
        self.assertEqual(len(self.rows()), 1)
        await self.begin(at=started)
        stale = self.driver.button("Далее")
        later = datetime(2026, 10, 15, 0, 0, tzinfo=UTC)
        await self.driver.text("/income", at=later)
        self.assertIn("сброшен", self.driver.texts())
        current = self.driver.button("Далее")
        await self.driver.click(data=stale)
        self.assertEqual(self.driver.button("Далее"), current)
        await self.driver.text("0,01")
        await self.to_comment()
        await self.finish()
        self.assertEqual(self.rows()[0].occurred_at, later)

    async def test_callback_start_uses_receipt_not_old_menu_date(self):
        await self.driver.text("/start")
        before = datetime.now(UTC)
        await self.driver.click("Потратил", message_date=datetime(2000, 1, 1, tzinfo=UTC))
        after = datetime.now(UTC)
        await self.driver.text("1")
        await self.to_comment()
        await self.finish()
        self.assertLessEqual(before, self.rows()[0].occurred_at)
        self.assertLessEqual(self.rows()[0].occurred_at, after)

    async def test_comment_preserve_replace_clear_cancel_and_create_clear(self):
        original = await self.create(comment="original")
        await self.edit_to_comment(original)
        self.assertIn("original", self.driver.latest().text)
        await self.finish()
        self.assertEqual(self.rows()[0].comment, "original")
        await self.edit_to_comment(original)
        await self.driver.text("replacement")
        self.assertEqual(self.rows()[0].comment, "original")
        await self.finish()
        self.assertEqual(self.rows()[0].comment, "replacement")
        await self.edit_to_comment(original)
        await self.driver.click("Очистить комментарий")
        self.assertEqual(self.rows()[0].comment, "replacement")
        self.assertIn(":comment:", self.driver.button("Далее"))
        await self.driver.click("Отменить")
        self.assertEqual(self.rows()[0].comment, "replacement")
        await self.edit_to_comment(original)
        await self.driver.click("Очистить комментарий")
        await self.finish()
        self.assertIsNone(self.rows()[0].comment)
        await self.begin("income")
        await self.to_comment()
        await self.driver.text("temporary")
        await self.driver.click("Очистить комментарий")
        await self.finish()
        self.assertTrue(all(row.comment is None for row in self.rows()))

