    async def test_concurrent_finish_creates_once_and_edits_once(self):
        with self.store.engine.begin() as connection:
            connection.execute(text("CREATE TABLE edit_audit (transaction_id TEXT)"))
            connection.execute(text("CREATE TRIGGER count_edits AFTER UPDATE ON transactions BEGIN INSERT INTO edit_audit VALUES (NEW.id); END"))
        await self.begin()
        await self.to_comment()
        finish = self.driver.button("Далее")
        await asyncio.gather(*(self.driver.click(data=finish) for _ in range(5)))
        self.assertEqual(len(self.rows()), 1)
        original = self.rows()[0]
        await self.edit(original)
        await self.driver.click("Далее")
        await self.driver.text("5")
        await self.to_comment()
        finish = self.driver.button("Далее")
        await asyncio.gather(*(self.driver.click(data=finish) for _ in range(5)))
        self.assertEqual((len(self.rows()), self.rows()[0].amount_kopecks), (1, 500))
        with self.store.engine.connect() as connection:
            self.assertEqual(connection.scalar(text("SELECT count(*) FROM edit_audit")), 1)

